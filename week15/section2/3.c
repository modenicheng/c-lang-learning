#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

// 判断是否可以从起点到达终点（递归实现）
int canReach(int x1, int y1, int x2, int y2) {
    // 如果起点等于终点，可以到达
    if (x1 == x2 && y1 == y2) {
        return 1;
    }

    // 如果起点坐标已经超过终点坐标，不可能到达（因为移动只增加坐标）
    if (x1 > x2 || y1 > y2) {
        return 0;
    }

    // 根据提示：判断能否从(x1,y1)到达(x2,y2)等价于
    // 判断能否从(x1, x1+y1)到达(x2,y2) 或 从(x1+y1, y1)到达(x2,y2)
    // 递归检查两个方向
    return canReach(x1, x1 + y1, x2, y2) || canReach(x1 + y1, y1, x2, y2);
}

int main() {
    int x1, y1, x2, y2;

    // 读取起点和终点坐标
    // 输入格式: "x, y" 可能有空格
    scanf("%d, %d", &x1, &y1);
    scanf("%d, %d", &x2, &y2);

    if (canReach(x1, y1, x2, y2)) {
        printf("Yes.\n");
    } else {
        printf("No.\n");
    }

    return 0;
}